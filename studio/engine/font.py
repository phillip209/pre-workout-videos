_ACC = {"Á": "A", "É": "E", "Í": "I", "Ó": "O", "Ú": "U", "Ñ": "N", "Ü": "U"}
SPACE_W = 3
CELL_H = 9


def _glyph(ch: str):
    """Return list of 9 row-strings for a character."""
    ch = ch.upper()
    if ch in _ACC:
        base = _G[_ACC[ch]]
        w = len(base[0])
        mid = w // 2
        if ch == "Ñ":
            top = [".##.#"[:w], "#.##."[:w]]
        elif ch == "Ü":
            top = ["." * w, (".#.#." if w == 5 else "#.#")[:w]]
        else:
            r0 = ["."] * w
            r1 = ["."] * w
            r0[min(w - 1, mid + 1)] = "#"
            r1[mid] = "#"
            top = ["".join(r0), "".join(r1)]
        return top + base
    g = _G.get(ch)
    if g is None:
        g = _G["?"]
    w = len(g[0])
    return ["." * w, "." * w] + g


def text_width(text: str, scale=1, spacing=1) -> int:
    w = 0
    for i, ch in enumerate(text):
        if ch == " ":
            w += SPACE_W + spacing
        else:
            w += len(_glyph(ch)[0]) + spacing
    return max(0, w - spacing) * scale


def draw_text(img: Image.Image, text: str, x: int, y: int, color=(255, 255, 255), scale=1,
              spacing=1, outline=None, shadow=None, colors=None, align="left", wave=None, t=0.0):
    """Draw text at (x,y) top-left (align='center' => x is centre).

    colors: optional per-character colour list (same length as text).
    outline: colour for a 1-scale-pixel outline. shadow: colour for drop shadow.
    wave: (amplitude_px, speed) for a bouncy per-letter wave.
    """
    import math

    if align == "center":
        x = int(round(x - text_width(text, scale, spacing) / 2))
    d = ImageDraw.Draw(img)
    cx = x
    for i, ch in enumerate(text):
        if ch == " ":
            cx += (SPACE_W + spacing) * scale
            continue
        rows = _glyph(ch)
        col = colors[i] if colors else color
        dy = 0
        if wave:
            dy = int(round(math.sin(t * wave[1] + i * 0.6) * wave[0]))
        pix = [(c, r) for r, row in enumerate(rows) for c, v in enumerate(row) if v == "#"]
        layers = []
        if shadow:
            layers.append((shadow, [(scale, scale)]))
        if outline:
            layers.append((outline, [(-scale, 0), (scale, 0), (0, -scale), (0, scale),
                                     (-scale, -scale), (scale, scale), (-scale, scale), (scale, -scale)]))
        layers.append((col, [(0, 0)]))
        for c_, offs in layers:
            for ox, oy in offs:
                for (c, r) in pix:
                    px = cx + c * scale + ox
                    py = y + r * scale + oy + dy
                    d.rectangle([px, py, px + scale - 1, py + scale - 1], fill=c_)
        cx += (len(rows[0]) + spacing) * scale
    return cx
